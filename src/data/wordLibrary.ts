/**
 * Returns a filtered and shuffled sample of preset words that the child
 * has NOT yet completed, ensuring fresh suggestions every time!
 */
export function getAvailablePresetWords(
  completedWordSet: Set<string>,
  wordTypeFilter: 'all' | WordType = 'all',
  count: number = 8,
  seedOffset: number = 0,
  currentLang: string = 'de'
): PresetWord[] {
  // Filter by category
  let candidateWords = PRESET_WORDS.filter(w => {
    if (wordTypeFilter !== 'all' && w.wordType !== wordTypeFilter) {
      return false;
    }
    // Exclude already completed words (check both DE and EN versions)
    const deMatch = completedWordSet.has(w.de.toLowerCase());
    const enMatch = completedWordSet.has(w.en.toLowerCase());
    return !(deMatch || enMatch);
  });

  // If all words in this category are completed, fallback so child is never blocked
  if (candidateWords.length === 0) {
    candidateWords = PRESET_WORDS.filter(w => {
      if (wordTypeFilter !== 'all' && w.wordType !== wordTypeFilter) {
        return false;
      }
      return true;
    });
  }

  // PRNG shuffle using seedOffset
  const shuffled = [...candidateWords];
  let seed = (seedOffset * 9301 + 49297) % 233280;
  for (let i = shuffled.length - 1; i > 0; i--) {
    seed = (seed * 9301 + 49297) % 233280;
    const rnd = seed / 233280;
    const j = Math.floor(rnd * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, count);
}
