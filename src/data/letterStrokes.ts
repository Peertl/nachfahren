export function getLetterData(char: string): LetterData {
  const norm = (char || '').normalize('NFC');
  if (CANONICAL_LETTER_STROKES[norm]) {
    return CANONICAL_LETTER_STROKES[norm];
  }

  const isUpper = char === char.toUpperCase() && char !== char.toLowerCase();
  return {
    char,
    isUpper,
    floors: isUpper ? ['roof', 'living'] : ['living'],
    strokes: [
      {
        id: 1,
        label: `1. Strich für ${char}`,
        start: { x: 35, y: isUpper ? 14 : 38 },
        end: { x: 35, y: 66 },
        pathD: `M 35 ${isUpper ? 14 : 38} L 35 66`,
        checkpoints: [{ x: 35, y: isUpper ? 40 : 52 }],
      },
      {
        id: 2,
        label: `2. Zweiter Strich für ${char}`,
        start: { x: 35, y: isUpper ? 14 : 38 },
        end: { x: 68, y: isUpper ? 40 : 52 },
        pathD: `M 35 ${isUpper ? 14 : 38} L 68 ${isUpper ? 40 : 52} L 35 66`,
        checkpoints: [{ x: 52, y: 46 }],
      },
    ],
  };
}
